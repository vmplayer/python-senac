itens = ["item 1", "item 2", "item 3"]

print(itens[0:])  # Imprime tudo

print(itens[1:3]) # Imprime do índice 1 até o índice 2
print(itens[1:])  # Imprime do índice 1 até o final
print(itens[:3])  # Imprime do início até o índice 2

print(itens[:-1]) # Imprime tudo
print(itens[-1:]) # Imprime do último até o final, ou seja, só o último